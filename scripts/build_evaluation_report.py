def error_chart(error_rows: list[dict[str, Any]]) -> Drawing:
    label_map = {
        "RESULT_CORRECT_PROCESS_INVALID": "答案正确/过程无效",
        "IMPLEMENTATION_MISMATCH": "实现不一致",
        "COMPLEXITY_TLE": "复杂度/TLE",
        "RUNTIME_ERROR": "运行错误",
        "WRONG_ALGORITHM": "错误算法",
    }
    rows = list(reversed(error_rows))
    drawing = Drawing(500, 225)
    chart = HorizontalBarChart()
    chart.x = 140
    chart.y = 35
    chart.height = 145
    chart.width = 325
    chart.data = [[row["count"] for row in rows]]
    chart.categoryAxis.categoryNames = [label_map.get(row["category"], row["category"]) for row in rows]
    chart.categoryAxis.labels.fontName = FONT
    chart.categoryAxis.labels.fontSize = 8
    chart.valueAxis.valueMin = 0
    chart.valueAxis.valueMax = max(row["count"] for row in rows) + 2
    chart.valueAxis.valueStep = 2
    chart.valueAxis.labels.fontName = FONT
    chart.valueAxis.labels.fontSize = 7
    chart.bars[0].fillColor = TEAL
    chart.strokeColor = BORDER
    drawing.add(chart)
    drawing.add(String(140, 198, "非严格成功运行的机器错误分类（n=35）", fontName=FONT_BOLD, fontSize=10, fillColor=NAVY))
    return drawing


class ReportDocTemplate(BaseDocTemplate):
    def __init__(self, filename: str):
        super().__init__(
            filename, pagesize=A4,
            rightMargin=1.8 * cm, leftMargin=1.8 * cm,
            topMargin=1.8 * cm, bottomMargin=1.7 * cm,
            title="Hy3-ContestLens 评测分析报告",
            author="Hy3-ContestLens 个人/活动作品",
            subject="过程评估、错误定位、有效性验证与人工抽检",
        )
        frame = Frame(self.leftMargin, self.bottomMargin, self.width, self.height, id="normal")
        self.addPageTemplates(PageTemplate(id="main", frames=[frame], onPage=self.draw_header_footer))

    def draw_header_footer(self, canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(BORDER)
        canvas.setLineWidth(0.5)
        canvas.line(self.leftMargin, A4[1] - 1.25 * cm, A4[0] - self.rightMargin, A4[1] - 1.25 * cm)
        canvas.setFont(FONT, 7.5)
        canvas.setFillColor(GRAY)
        canvas.drawString(self.leftMargin, A4[1] - 1.05 * cm, "Hy3-ContestLens 评测分析报告")
        canvas.drawRightString(A4[0] - self.rightMargin, 0.85 * cm, f"第 {doc.page} 页")
        canvas.restoreState()


def audit_summary_rows(audits: list[dict[str, str]]) -> list[list[str]]:
    rows = [["题目", "类别", "机器首错", "人工复核", "人工真值首错", "结论"]]
    for row in audits:
        kind = "正确答案告警" if row["review_kind"] == "correct_answer_flagged" else "错误答案定位"
        process = row.get("human_actual_process_correct")
        if process == "True":
            review = "过程正确"
        elif process == "False":
            review = "存在过程问题"
        else:
            review = "待定"
        rows.append([
            row.get("title_zh") or row["problem_id"],
            kind,
            row.get("machine_first_error_step_id") or "未定位",
            review,
            row.get("human_actual_first_error_step_id") or "无",
            row.get("assisted_review_conclusion") or "",
        ])
    return rows


