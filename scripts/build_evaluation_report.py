def styled_table(
    rows: list[list[Any]],
    widths: list[float],
    *,
    repeat_rows: int = 1,
    alignments: dict[int, str] | None = None,
    highlights: list[tuple[int, colors.Color]] | None = None,
    font_size: float = 7.7,
) -> Table:
    cooked: list[list[Any]] = []
    for row_index, row in enumerate(rows):
        style = STYLES["table_head"] if row_index < repeat_rows else STYLES["table"]
        cooked.append([cell if isinstance(cell, Paragraph) else p(str(cell), style) for cell in row])
    table = Table(cooked, colWidths=widths, repeatRows=repeat_rows, hAlign="LEFT")
    commands: list[tuple] = [
        ("BACKGROUND", (0, 0), (-1, repeat_rows - 1), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, repeat_rows - 1), colors.white),
        ("FONTNAME", (0, 0), (-1, repeat_rows - 1), FONT_BOLD),
        ("FONTNAME", (0, repeat_rows), (-1, -1), FONT),
        ("FONTSIZE", (0, 0), (-1, -1), font_size),
        ("LEADING", (0, 0), (-1, -1), font_size + 3),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (0, 0), (-1, repeat_rows - 1), "CENTER"),
        ("GRID", (0, 0), (-1, 0), 0.5, NAVY),
        ("LINEBELOW", (0, repeat_rows), (-1, -1), 0.25, BORDER),
        ("ROWBACKGROUNDS", (0, repeat_rows), (-1, -1), [colors.white, LIGHT_GRAY]),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for column, alignment in (alignments or {}).items():
        commands.append(("ALIGN", (column, repeat_rows), (column, -1), alignment))
    for row_index, fill in (highlights or []):
        commands.append(("BACKGROUND", (0, row_index), (-1, row_index), fill))
    table.setStyle(TableStyle(commands))
    return table


def callout(title: str, text: str, *, tone: str = "blue") -> Table:
    palette = {
        "blue": (PALE_BLUE, NAVY),
        "amber": (PALE_AMBER, AMBER),
        "red": (PALE_RED, RED),
        "green": (PALE_GREEN, GREEN),
    }
    fill, ink = palette[tone]
    title_style = ParagraphStyle(
        "CalloutTitle", parent=STYLES["callout"], fontName=FONT_BOLD, textColor=ink,
    )
    table = Table([[p(title, title_style)], [p(text, STYLES["callout"]) ]], colWidths=[17.0 * cm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), fill),
        ("BOX", (0, 0), (-1, -1), 0.8, ink),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return table


