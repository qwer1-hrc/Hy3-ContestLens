def register_fonts() -> tuple[str, str]:
    candidates = [
        ("MSYH", Path(r"C:\Windows\Fonts\msyh.ttc"), "MSYH-Bold", Path(r"C:\Windows\Fonts\msyhbd.ttc")),
        ("SimSun", Path(r"C:\Windows\Fonts\simsun.ttc"), "SimHei", Path(r"C:\Windows\Fonts\simhei.ttf")),
    ]
    for regular_name, regular_path, bold_name, bold_path in candidates:
        try:
            pdfmetrics.registerFont(TTFont(regular_name, str(regular_path)))
            pdfmetrics.registerFont(TTFont(bold_name, str(bold_path)))
            pdfmetrics.registerFontFamily(
                "ReportCJK", normal=regular_name, bold=bold_name,
                italic=regular_name, boldItalic=bold_name,
            )
            pdfmetrics.registerFontFamily(
                regular_name, normal=regular_name, bold=bold_name,
                italic=regular_name, boldItalic=bold_name,
            )
            return regular_name, bold_name
        except Exception:
            continue
    raise RuntimeError("No usable Chinese TrueType font was found.")


